pub const REBOOT_INITIATED: i64 = -1978334965;

/// `{code, hex, symbol, description, known}` for a 32-bit exit code.
pub fn describe(code: i64) -> Value {
    match CODES.iter().find(|c| c.0 == code) {
        Some((c, h, s, d)) => {
            json!({"code": c, "hex": h, "symbol": s, "description": d, "known": true})
        }
        None => {
            json!({"code": code, "hex": format!("0x{:08X}", code as u32), "symbol": null, "description": null, "known": false})
        }
    }
}

